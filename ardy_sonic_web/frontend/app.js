function updateTrackingError(actual) {
  const frame = currentReferenceFrame();
  const localFrame = frame - (Number(state.motionHeader?.frame_origin) || 0);
  const telemetryJoints = state.referenceTelemetry?.reference_joint_pos;
  if (!telemetryJoints && (!state.reference || !state.motionHeader || localFrame < 0 || localFrame >= state.motionHeader.shape[0])) return;
  let squared = 0;
  for (let index = 0; index < 29; index += 1) {
    const referenceJoint = telemetryJoints
      ? telemetryJoints[index]
      : state.reference[localFrame * 36 + 7 + index];
    let delta = referenceJoint - actual[index + 7];
    delta = Math.atan2(Math.sin(delta), Math.cos(delta));
    squared += delta * delta;
  }
  const errorDeg = Math.sqrt(squared / 29) * 180 / Math.PI;
  state.trackingErrorDeg.push(errorDeg);
  byId("tracking-error").textContent = `${errorDeg.toFixed(1)}°`;
}

function receiveReferenceTelemetry(telemetry) {
  const joints = telemetry.reference_joint_pos;
  const rootPos = telemetry.reference_root_pos;
  const rootQuat = telemetry.reference_root_quat;
  if (
    telemetry.version !== 1
    || !Number.isInteger(telemetry.current_frame_global)
    || telemetry.current_frame_global < 0
    || !Array.isArray(joints) || joints.length !== 29
    || !Array.isArray(rootPos) || rootPos.length !== 3
    || !Array.isArray(rootQuat) || rootQuat.length !== 4
  ) {
    throw new Error("Invalid SONIC reference telemetry");
  }
  const packetEpoch = Number.isInteger(telemetry.epoch_id) ? telemetry.epoch_id : state.epochId;
  if (packetEpoch < state.epochId) return;
  if (packetEpoch > state.epochId) {
    state.actualBuffer.length = 0;
    state.referenceTelemetryBuffer.length = 0;
    state.actualClockOffsetMs = null;
    state.referenceClockOffsetMs = null;
    state.transportBaselineMs = null;
    state.epochId = packetEpoch;
    actualPlayout.reset(); referencePlayout.reset();
  }
  state.referenceTelemetry = telemetry;
  state.refFrame = telemetry.current_frame_global;
  const arrival = performance.now();
  const sourceSeconds = telemetry.current_frame_global / Number(telemetry.reference_fps);
  referencePlayout.observe(sourceSeconds, arrival);
  const observedOffset = arrival - sourceSeconds * 1000;
  state.referenceClockOffsetMs = state.referenceClockOffsetMs == null
    ? observedOffset
    : state.referenceClockOffsetMs * 0.9 + observedOffset * 0.1;
  const qpos = new Float32Array(36);
  qpos.set(rootPos, 0); qpos.set(rootQuat, 3); qpos.set(joints, 7);
  state.referenceTelemetryBuffer.push({ telemetry, arrival, sourceSeconds, qpos });
  if (state.referenceTelemetryBuffer.length > 8) state.referenceTelemetryBuffer.shift();
}

function receiveControl(raw) {
  const control = JSON.parse(raw);
  if (control.type === "reference_telemetry") {
    receiveReferenceTelemetry(control);
    return;
  }
  if (control.type !== "control" || control.version !== 1) return;
  if (Number.isInteger(control.epoch_id)) {
    if (control.epoch_id < state.epochId) return;
    if (control.epoch_id > state.epochId) {
      state.epochId = control.epoch_id;
      state.actualBuffer.length = 0;
      state.referenceTelemetryBuffer.length = 0;
      state.actualClockOffsetMs = null;
      state.referenceClockOffsetMs = null;
      state.transportBaselineMs = null;
      actualPlayout.reset(); referencePlayout.reset();
      state.referenceTelemetry = null;
    }
  }
  if (control.debug_mode) {
    state.debugMode = control.debug_mode;
    updateDebugModeUi();
  }
  const origin = Number(state.motionHeader?.frame_origin) || 0;
  const last = origin + Math.max(0, (state.motionHeader?.shape?.[0] || 1) - 1);
  state.refFrame = clamp(Number.isFinite(control.frame) ? control.frame : state.refFrame, origin, last);
  if (control.action === "play") state.playing = true;
  if (["pause", "restart", "reset"].includes(control.action)) state.playing = false;
  if (["restart", "reset"].includes(control.action)) state.refFrame = 0;
  if (control.action === "sync" && typeof control.playing === "boolean") state.playing = control.playing;
  anchorPlayback();
  updateMotionName(state.refFrame);
}

function anchorPlayback() {
  state.playStartedAt = performance.now();
  state.playStartedFrame = state.refFrame;
}

function currentReferenceFrame() {
  return Math.floor(currentReferenceFrameFloat());
}

function currentReferenceFrameFloat() {
  if (state.referenceTelemetry && state.referenceClockOffsetMs != null) {
    const fps = Number(state.referenceTelemetry.reference_fps);
    return Math.max(0, referencePlayout.sample(performance.now()) * fps);
  }
  if (!state.motionHeader) return 0;
  // Live SONIC follows consumption, including its startup/alignment wait.
  // Do not play the whole reference locally while the policy is still frozen.
  if (state.debugMode === "ardy_streaming") return Number(state.refFrame);
  if (!state.playing) return Number(state.refFrame);
  const elapsed = (performance.now() - state.playStartedAt) / 1000;
  const frame = state.playStartedFrame + elapsed * state.motionHeader.fps;
  const last = (Number(state.motionHeader.frame_origin) || 0) + state.motionHeader.shape[0] - 1;
  if (frame >= last) {
    state.refFrame = last;
    state.playing = false;
    return last;
  }
  return frame;
}

function interpolateQpos(first, second, alpha, output) {
  const a = first.qpos;
  const b = second.qpos;
  const t = clamp(alpha, 0, 1);
  for (let index = 0; index < 3; index += 1) output[index] = a[index] + (b[index] - a[index]) * t;

  let aw = a[3], ax = a[4], ay = a[5], az = a[6];
  let bw = b[3], bx = b[4], by = b[5], bz = b[6];
  let dot = aw * bw + ax * bx + ay * by + az * bz;
  if (dot < 0) { dot = -dot; bw = -bw; bx = -bx; by = -by; bz = -bz; }
  let scaleA;
  let scaleB;
  if (dot > 0.9995) {
    scaleA = 1 - t;
    scaleB = t;
  } else {
    const theta = Math.acos(clamp(dot, -1, 1));
    const sinTheta = Math.sin(theta);
    scaleA = Math.sin((1 - t) * theta) / sinTheta;
    scaleB = Math.sin(t * theta) / sinTheta;
  }
  output[3] = aw * scaleA + bw * scaleB;
  output[4] = ax * scaleA + bx * scaleB;
  output[5] = ay * scaleA + by * scaleB;
  output[6] = az * scaleA + bz * scaleB;

  for (let index = 7; index < 36; index += 1) {
    const delta = Math.atan2(Math.sin(b[index] - a[index]), Math.cos(b[index] - a[index]));
    output[index] = a[index] + delta * t;
  }
}

function sampleActual(now) {
  const samples = state.actualBuffer;
  if (!samples.length) return null;
  if (state.actualClockOffsetMs == null || !Number.isFinite(Number(samples[0].header.sim_time))) {
    state.presentedActualSimTime = Number(samples.at(-1).header.sim_time);
    return samples.at(-1).qpos;
  }
  const target = actualPlayout.sample(now);
  const firstSimTime = Number(samples[0].header.sim_time);
  if (target <= firstSimTime) {
    state.presentedActualSimTime = firstSimTime;
    return samples[0].qpos;
  }
  const newest = samples.at(-1);
  const newestSimTime = Number(newest.header.sim_time);
  if (target >= newestSimTime) {
    state.presentedActualSimTime = newestSimTime;
    return newest.qpos;
  }
  for (let index = samples.length - 2; index >= 0; index -= 1) {
    const first = samples[index];
    const second = samples[index + 1];
    const firstTime = Number(first.header.sim_time);
    const secondTime = Number(second.header.sim_time);
    if (firstTime <= target && secondTime > firstTime) {
      interpolateQpos(first, second, (target - firstTime) / (secondTime - firstTime), state.renderQpos);
      state.presentedActualSimTime = target;
      return state.renderQpos;
    }
  }
  return samples[0].qpos;
}

function sampleReference() {
  const telemetrySamples = state.referenceTelemetryBuffer;
  if (telemetrySamples.length) {
    const target = state.referenceClockOffsetMs == null
      ? telemetrySamples.at(-1).sourceSeconds
      : referencePlayout.sample(performance.now());
    let first = telemetrySamples[0];
    let second = telemetrySamples.at(-1);
    for (let index = telemetrySamples.length - 1; index > 0; index -= 1) {
      if (telemetrySamples[index - 1].sourceSeconds <= target) {
        first = telemetrySamples[index - 1];
        second = telemetrySamples[index];
        break;
      }
    }
    interpolateQpos(first, second,
      second.sourceSeconds > first.sourceSeconds
        ? (target - first.sourceSeconds) / (second.sourceSeconds - first.sourceSeconds) : 0,
      state.renderReferenceQpos);
    state.presentedReferenceTime = clamp(target, first.sourceSeconds, second.sourceSeconds);
    return state.renderReferenceQpos;
  }
  if (!state.reference || !state.motionHeader) return null;
  const origin = Number(state.motionHeader.frame_origin) || 0;
  const last = state.motionHeader.shape[0] - 1;
  const frame = clamp(currentReferenceFrameFloat() - origin, 0, last);
  state.presentedReferenceTime = (frame + origin) / Number(state.motionHeader.fps);
  const firstIndex = Math.floor(frame);
  const secondIndex = Math.min(firstIndex + 1, last);
  const first = state.reference.subarray(firstIndex * 36, firstIndex * 36 + 36);
  if (firstIndex === secondIndex) return first;
  const second = state.reference.subarray(secondIndex * 36, secondIndex * 36 + 36);
  interpolateQpos(
    { qpos: first },
    { qpos: second },
    frame - firstIndex,
    state.renderReferenceQpos,
  );
  return state.renderReferenceQpos;
}

function connect() {
  const scheme = location.protocol === "https:" ? "wss" : "ws";
  const socket = new WebSocket(`${scheme}://${location.host}/ws/consumer`);
  socket.binaryType = "arraybuffer";
  state.socket = socket;
  socket.onopen = () => { state.reconnectMs = 500; };
  socket.onmessage = async (event) => {
    try {
      if (typeof event.data === "string") receiveControl(event.data);
      else {
        const buffer = event.data instanceof Blob ? await event.data.arrayBuffer() : event.data;
        const magic = textDecoder.decode(new Uint8Array(buffer, 0, 4));
        if (magic === "ASB1") receiveMotion(buffer);
        else if (magic === "AST1") receiveActual(buffer);
      }
    } catch (error) {
      console.error("SONIC bridge packet error", error);
      showToast(error.message);
    }
  };
  socket.onclose = () => {
    window.setTimeout(connect, state.reconnectMs);
    state.reconnectMs = Math.min(state.reconnectMs * 2, 5000);
  };
  socket.onerror = () => socket.close();
}

function sendViewerControl(action, values = {}) {
  if (state.socket?.readyState !== WebSocket.OPEN) return;
  state.socket.send(JSON.stringify({ type: "viewer_control", version: 1, action, ...values }));
}

