function parsePacket(buffer, expectedMagic) {
  const bytes = new Uint8Array(buffer);
  if (bytes.length < 8 || textDecoder.decode(bytes.subarray(0, 4)) !== expectedMagic) {
    throw new Error(`Invalid ${expectedMagic} packet`);
  }
  const headerLength = new DataView(buffer).getUint32(4, true);
  const payloadOffset = 8 + headerLength;
  if (headerLength <= 0 || payloadOffset > bytes.length) throw new Error("Invalid packet header");
  const header = JSON.parse(textDecoder.decode(bytes.subarray(8, payloadOffset)));
  if (header.version !== 1 || header.dtype !== "f32" || header.endian !== "little") {
    throw new Error("Unsupported bridge packet version");
  }
  return { header, payloadOffset };
}

function receiveMotion(buffer) {
  const { header, payloadOffset } = parsePacket(buffer, "ASB1");
  const [frames, nq] = header.shape || [];
  if (nq !== 36 || frames < 2 || buffer.byteLength - payloadOffset !== frames * nq * 4) {
    throw new Error("Invalid G1 reference motion");
  }
  const packetEpoch = Number.isInteger(header.epoch_id) ? header.epoch_id : state.epochId;
  if (packetEpoch < state.epochId) return;
  const announceLoad = !state.motionHeader || packetEpoch > state.epochId
    || header.debug_mode !== "ardy_streaming";
  if (packetEpoch > state.epochId) {
    state.actualBuffer.length = 0;
    state.referenceTelemetryBuffer.length = 0;
    state.actualClockOffsetMs = null;
    state.referenceClockOffsetMs = null;
    state.transportBaselineMs = null;
    state.epochId = packetEpoch;
    actualPlayout.reset(); referencePlayout.reset();
    state.referenceTelemetry = null;
  }
  state.motionHeader = header;
  byId("source-label").textContent = String(header.name).includes("Motion Mamba 2.0")
    ? "Reference generated by Motion Mamba 2.0" : "Reference generated by ARDY";
  state.reference = new Float32Array(buffer.slice(payloadOffset));
  state.debugMode = header.debug_mode || "ardy_streaming";
  if (!state.referenceTelemetry) {
    const origin = Number(header.frame_origin) || 0;
    state.refFrame = clamp(Number(header.current_frame) || origin, origin, origin + frames - 1);
    state.playing = Boolean(header.playing);
    anchorPlayback();
  }

  const name = motionNameForFrame(currentReferenceFrame());
  byId("motion-name").textContent = name;
  byId("motion-meta").textContent = `${frames} frames · ${Number(header.fps).toFixed(0)} fps`;
  byId("info-motion").textContent = name;
  updateDebugModeUi();
  if (announceLoad) showToast(`Loaded ${frames} reference frames`);
}

function motionNameForFrame(frame) {
  const fallback = state.motionHeader?.name || "ARDY Live";
  const segments = state.motionHeader?.prompt_segments;
  if (!Array.isArray(segments)) return fallback;
  let activeName = fallback;
  for (const segment of segments) {
    const start = Number(segment?.start_frame);
    const end = Number(segment?.end_frame);
    if (!Number.isFinite(start) || !Number.isFinite(end) || frame < start) continue;
    if (frame <= end && typeof segment.text === "string" && segment.text.length) {
      activeName = segment.text;
    }
  }
  return activeName;
}

function updateMotionName(frame) {
  const name = motionNameForFrame(frame);
  if (name === state.displayedMotionName) return;
  state.displayedMotionName = name;
  byId("motion-name").textContent = name;
  byId("info-motion").textContent = name;
}

function receiveActual(buffer) {
  const { header, payloadOffset } = parsePacket(buffer, "AST1");
  if (header.qpos_count !== 36 || header.qvel_count !== 35 || buffer.byteLength - payloadOffset !== 284) {
    throw new Error("Invalid SONIC actual state");
  }
  const qpos = new Float32Array(buffer.slice(payloadOffset, payloadOffset + 36 * 4));
  const qvel = new Float32Array(buffer.slice(payloadOffset + 36 * 4));
  const arrival = performance.now();
  const packetEpoch = Number.isInteger(header.epoch_id) ? header.epoch_id : state.epochId;
  if (packetEpoch < state.epochId) return;
  if (packetEpoch > state.epochId) {
    state.epochId = packetEpoch;
    state.actualBuffer.length = 0;
    state.referenceTelemetryBuffer.length = 0;
    state.actualClockOffsetMs = null;
    state.referenceClockOffsetMs = null;
    state.transportBaselineMs = null;
    actualPlayout.reset(); referencePlayout.reset();
    state.referenceTelemetry = null;
  }
  const previous = state.actualBuffer.at(-1);
  const simTime = Number(header.sim_time);
  const previousSimTime = Number(previous?.header?.sim_time);

  if (previous && Number.isFinite(simTime) && Number.isFinite(previousSimTime)) {
    if (simTime < previousSimTime - 0.1) state.actualBuffer.length = 0;
    // Frozen physics still publishes current liveness/physics flags. Do not
    // mistake a paused clock for a lost connection or append duplicate poses.
  }

  if (Number.isFinite(simTime)) {
    const observedOffset = arrival - simTime * 1000;
    state.actualClockOffsetMs = state.actualClockOffsetMs == null
      ? observedOffset
      : state.actualClockOffsetMs * 0.9 + observedOffset * 0.1;
  }
  const producerMonotonic = Number(header.monotonic_timestamp);
  if (Number.isFinite(producerMonotonic)) {
    const observed = arrival - producerMonotonic * 1000;
    state.transportBaselineMs = state.transportBaselineMs == null
      ? observed : Math.min(state.transportBaselineMs, observed);
    state.transportDelayMs.push(Math.max(0, observed - state.transportBaselineMs));
  }

  actualPlayout.observe(simTime, arrival);
  if (!previous || simTime > previousSimTime || simTime < previousSimTime - 0.1) {
    state.actualBuffer.push({ header, qpos, qvel, arrival });
  } else {
    previous.header = header;
  }
  if (state.actualBuffer.length > MAX_ACTUAL_SAMPLES) state.actualBuffer.shift();
  state.latestActualAt = arrival;
  state.receiveTimes.push(arrival);
  while (state.receiveTimes.length && arrival - state.receiveTimes[0] > 1000) state.receiveTimes.shift();

  if (typeof header.physics === "boolean" && header.physics !== state.physics) {
    state.physics = header.physics;
    setToggle("btn-physics", state.physics);
    byId("info-physics").textContent = state.physics ? "ON" : "OFF";
  }

  if (arrival - state.lastStatusUpdateAt >= 100) {
    state.lastStatusUpdateAt = arrival;
    byId("info-actual").textContent = `${state.receiveTimes.length} Hz`;
    byId("info-actual").classList.add("actual-on");
    byId("status-dot").className = header.fallen ? "status-dot error" : "status-dot ready";
    byId("status-text").textContent = header.fallen
      ? "Fall detected — Restart required"
      : !header.physics ? "Paused"
      : state.policy ? "Policy running" : "Physics running";
    updateTrackingError(qpos);
    byId("actual-root").textContent = formatVector(qpos.subarray(0, 3), "m");
    byId("actual-velocity").textContent = formatVector(qvel.subarray(0, 3), "m/s");
  }
}

function formatVector(values, unit) {
  return `${Array.from(values, (value) => Number(value).toFixed(2)).join(", ")} ${unit}`;
}

