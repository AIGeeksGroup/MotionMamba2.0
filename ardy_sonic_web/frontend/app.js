function toggleFollow() {
  state.follow = !state.follow;
  setToggle("btn-follow", state.follow);
  viewer.setFollow(state.follow);
}

function restart() {
  state.actualBuffer.length = 0;
  sendViewerControl("restart");
  showToast("SONIC simulation restart requested");
}

function setPlayback(playing) {
  if (!state.motionHeader) {
    showToast("尚未收到动作，请等待离线动作加载");
    return;
  }
  sendViewerControl(playing ? "play" : "pause");
  showToast(playing ? "准备播放：等待 SONIC 就绪" : "已请求暂停");
}

let toastTimer = 0;
function showToast(message) {
  const toast = byId("toast");
  toast.textContent = message;
  toast.classList.add("visible");
  clearTimeout(toastTimer);
  toastTimer = window.setTimeout(() => toast.classList.remove("visible"), 1800);
}

function wireControls() {
  byId("play-button").onclick = () => setPlayback(true);
  byId("pause-button").onclick = () => setPlayback(false);
  byId("btn-physics").onclick = togglePhysics;
  byId("physics-button").onclick = togglePhysics;
  byId("btn-policy").onclick = togglePolicy;
  byId("policy-button").onclick = togglePolicy;
  byId("btn-follow").onclick = toggleFollow;
  byId("hand-style").onchange = (event) => viewer.setHandStyle(event.target.value);
  byId("follow-button").onclick = toggleFollow;
  byId("restart-button").onclick = restart;
  document.addEventListener("keydown", (event) => {
    if (event.repeat) return;
    if (event.code === "Space" && !/INPUT|TEXTAREA|SELECT/.test(event.target.tagName)) {
      event.preventDefault();
      setPlayback(!state.playing);
    }
    if (event.key.toLowerCase() === "p") togglePhysics();
    if (event.key.toLowerCase() === "o") togglePolicy();
    if (event.key.toLowerCase() === "r") restart();
    if (event.key.toLowerCase() === "f") toggleFollow();
  });
}

function render(now) {
  requestAnimationFrame(render);
  const referenceQpos = sampleReference();
  const qpos = state.debugMode === "reference_only" ? referenceQpos : sampleActual(now);
  if (qpos && viewer.ready) viewer.setQpos(qpos);
  viewer.render();

  if (state.presentedActualSimTime != null && state.presentedReferenceTime != null) {
    state.presentationSkewMs.push(Math.abs(
      state.presentedReferenceTime - state.presentedActualSimTime,
    ) * 1000);
  }

  const frame = currentReferenceFrame();
  updateMotionName(frame);
  const count = state.motionHeader?.shape?.[0] || 0;
  const origin = Number(state.motionHeader?.frame_origin) || 0;
  const lastFrame = count > 0 ? origin + count - 1 : 0;
  const fps = state.referenceTelemetry?.reference_fps || state.motionHeader?.fps || 50;
  const duration = lastFrame / fps;
  if (now - state.lastRenderUiAt >= 100) {
    state.lastRenderUiAt = now;
    byId("ref-frame").textContent = `${frame} / ${lastFrame}`;
    byId("ref-time").textContent = `${(frame / fps).toFixed(2)} / ${duration.toFixed(2)} s`;
    if (referenceQpos) {
      byId("ref-root").textContent = formatVector(referenceQpos.subarray(0, 3), "m");
    }
  }

  state.renderFrames += 1;
  const elapsed = now - state.fpsStartedAt;
  if (elapsed >= 1000) {
    state.renderFps = Math.round(state.renderFrames * 1000 / elapsed);
    state.renderFrames = 0;
    state.fpsStartedAt = now;
    byId("status-fps").textContent = `${state.renderFps} render fps · ${state.receiveTimes.length} Hz state`;
    if (state.presentationSkewMs.length) {
      const sorted = state.presentationSkewMs.sort((a, b) => a - b);
      const percentile = (value) => sorted[Math.min(sorted.length - 1, Math.floor((sorted.length - 1) * value))];
      console.info(
        "[SONIC presentation diagnostic]",
        `render_buffer_ms=${RENDER_DELAY_MS}`,
        `clock_skew_p50_ms=${percentile(0.5).toFixed(2)}`,
        `clock_skew_p95_ms=${percentile(0.95).toFixed(2)}`,
        `actual_receive_hz=${state.receiveTimes.length}`,
        `canvas_css=${byId("canvas").clientWidth}x${byId("canvas").clientHeight}`,
        `drawing_buffer=${byId("canvas").width}x${byId("canvas").height}`,
        `dpr=${window.devicePixelRatio.toFixed(2)}`,
      );
      state.presentationSkewMs.length = 0;
    }
    if (state.transportDelayMs.length) {
      const transport = state.transportDelayMs.sort((a, b) => a - b);
      const tracking = state.trackingErrorDeg.sort((a, b) => a - b);
      const p = (values, value) => values[Math.min(values.length - 1, Math.floor((values.length - 1) * value))];
      console.info(
        "[SONIC separated diagnostics]",
        `network_forward_p50_ms=${p(transport, 0.5).toFixed(2)}`,
        `network_forward_p95_ms=${p(transport, 0.95).toFixed(2)}`,
        `browser_presentation_delay_ms=${RENDER_DELAY_MS}`,
        tracking.length ? `policy_tracking_p50_deg=${p(tracking, 0.5).toFixed(2)}` : "policy_tracking=unavailable",
        tracking.length ? `policy_tracking_p95_deg=${p(tracking, 0.95).toFixed(2)}` : "",
      );
      state.transportDelayMs.length = 0;
      state.trackingErrorDeg.length = 0;
    }
  }

  if (state.debugMode !== "reference_only" && state.latestActualAt && now - state.latestActualAt > 1200) {
    byId("status-dot").className = "status-dot loading";
    byId("status-text").textContent = "Actual state waiting";
    byId("info-actual").textContent = "WAIT";
    byId("info-actual").classList.remove("actual-on");
  }
}

async function main() {
  wireControls();
  connect();
  requestAnimationFrame(render);
  try {
    await viewer.init();
    byId("loading-overlay").classList.add("fade-out");
    window.setTimeout(() => { byId("loading-overlay").hidden = true; }, 600);
    byId("status-text").textContent = state.debugMode === "reference_only"
      ? "Reference only"
      : (state.actualBuffer.length ? "Policy running" : "Actual state waiting");
  } catch (error) {
    console.error(error);
    byId("loading-status").textContent = `Error: ${error.message}`;
    byId("status-dot").className = "status-dot error";
    byId("status-text").textContent = "Viewer load failed";
  }
}

main();

